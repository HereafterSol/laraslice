<?php

namespace LaraSlice\Commands;

use Illuminate\Console\Command;
use LaraSlice\Core\Discovery\SliceManager;

class SliceRepairCommand extends Command
{
    protected $signature = 'slice:repair
                            {slice? : Repair only this slice}
                            {--dry-run : List the files that would change without writing them}
                            {--publish-ui : Force-publish BlatUI components (data-table, etc.) from package stubs}
                            {--remap-nav : Re-stamp navigation.group from porting module map (Work/Finance/HR…)}
                            {--re-infer-ui : Re-generate directory UI config from fields using current formatter inference}
                            {--source= : ERP/source project path for Phase 2 *DataTable.php classification}
                            {--merge-config : Merge missing keys from package config into published config/laraslice.php}';

    protected $description = 'Upgrade files of slices generated by older LaraSlice versions to the current layout';

    public function handle(SliceManager $manager): int
    {
        $manager->discover();

        $name = $this->argument('slice');
        $slices = $name ? array_filter([$manager->getSlice($name)]) : $manager->getAllSlices();
        if ($name && $slices === []) {
            $this->error("Slice [{$name}] not found.");

            return self::FAILURE;
        }

        $dryRun = (bool) $this->option('dry-run');
        $changed = 0;
        if ($this->option('publish-ui') && ! $dryRun) {
            $this->publishBlatUiComponents();
        }

        if (! $dryRun && ($this->option('merge-config') || true)) {
            // Always soft-merge missing package config keys (e.g. auth.mfa_enabled)
            $this->mergePublishedLarasliceConfig();
        }
        if ($this->option('remap-nav') && ! $dryRun) {
            $changed += $this->remapNavigationGroups($manager, $slices);
        }
        if ($this->option('re-infer-ui')) {
            $source = $this->option('source') ?: null;
            $changed += $this->reInferDirectoryUi($manager, $slices, $dryRun, is_string($source) ? $source : null);
        }
        foreach ($slices as $slice) {
            foreach ($manager->repairSlice($slice, $dryRun) as $file) {
                $this->line(($dryRun ? '<fg=yellow>would update</> ' : '<fg=green>updated</> ').$file);
                $changed++;
            }
        }

        $this->info($changed === 0
            ? 'All slices are up to date.'
            : ($dryRun ? "{$changed} file(s) would be updated; run without --dry-run to apply." : "{$changed} file(s) updated."));

        
        $this->reportJsonOnlySlices();

        return self::SUCCESS;
    }

    protected function publishBlatUiComponents(): void
    {
        $src = dirname(__DIR__, 2).'/resources/stubs/starter/views/components/ui';
        $dest = resource_path('views/components/ui');
        if (! is_dir($src)) {
            $this->warn('BlatUI stubs not found at '.$src);

            return;
        }
        if (! is_dir($dest)) {
            mkdir($dest, 0755, true);
        }
        $count = 0;
        $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($src, \FilesystemIterator::SKIP_DOTS));
        foreach ($it as $file) {
            if (! $file->isFile()) {
                continue;
            }
            $rel = substr($file->getPathname(), strlen($src) + 1);
            $target = $dest.DIRECTORY_SEPARATOR.$rel;
            $dir = dirname($target);
            if (! is_dir($dir)) {
                mkdir($dir, 0755, true);
            }
            if (copy($file->getPathname(), $target)) {
                $count++;
                $this->line("<fg=green>published</> components/ui/{$rel}");
            }
        }
        $this->info("Published {$count} BlatUI component file(s) to resources/views/components/ui.");
    }

    /**
     * Re-apply demo-aligned module groups (Work, Finance, HR, CRM, …) onto existing slice.json + slice.yaml.
     */
    protected function remapNavigationGroups(\LaraSlice\Core\Discovery\SliceManager $manager, array $slices): int
    {
        $porter = app(\LaraSlice\Porting\SlicePortService::class);
        $n = 0;
        foreach ($slices as $slice) {
            $json = $slice->path.'/slice.json';
            if (! is_file($json)) {
                continue;
            }
            try {
                $manifest = \LaraSlice\Core\Discovery\ManifestRepository::read($json);
            } catch (\Throwable $e) {
                continue;
            }
            $primary = $manifest['models'][0]['table'] ?? \Illuminate\Support\Str::snake($slice->name);
            $module = $porter->detectModuleForSlice($slice->name, $primary);
            $old = $manifest['navigation']['group'] ?? null;
            $manifest['navigation'] = array_merge($manifest['navigation'] ?? [], [
                'group' => $module,
            ]);
            // Hide common noise if still visible roots
            $noise = ['ItemTaxes', 'TransactionTaxes', 'BillHistories', 'Categories', 'Dashboards', 'Documents', 'Accounts', 'Taxes', 'Recurrings'];
            if (in_array($slice->name, $noise, true) || str_ends_with($slice->name, 'Items')) {
                $manifest['navigation']['visible'] = false;
            }
            \LaraSlice\Core\Discovery\ManifestRepository::writeBoth($json, $manifest);
            $this->line("<fg=green>remap-nav</> {$slice->name}: ".($old ?: '—')." → {$module}");
            $n++;
        }
        $manager->clearCache();
        $this->info("Remapped navigation.group on {$n} slice(s).");

        return $n;
    }

    /**
     * Re-generate directory UI config from the slice's fields using the
     * current formatter inference. Skips slices with Studio version_history
     * to avoid clobbering user customizations.
     */
    protected function reInferDirectoryUi(\LaraSlice\Core\Discovery\SliceManager $manager, array $slices, bool $dryRun, ?string $sourcePath = null): int
    {
        $porter = app(\LaraSlice\Porting\SlicePortService::class);
        $n = 0;
        $skipped = 0;
        if ($sourcePath) {
            $this->line("<fg=gray>Phase 2 source:</> {$sourcePath}");
        }
        foreach ($slices as $slice) {
            $json = $slice->path.'/slice.json';
            if (! is_file($json)) {
                continue;
            }
            try {
                $manifest = \LaraSlice\Core\Discovery\ManifestRepository::read($json);
            } catch (\Throwable $e) {
                continue;
            }

            // Don't clobber Studio customizations
            if (! empty($manifest['version_history'])) {
                $skipped++;
                $this->line("<fg=yellow>skip</> {$slice->name}: has Studio version_history (user customized)");
                continue;
            }

            $fields = $manifest['fields'] ?? [];
            if (empty($fields)) {
                continue;
            }

            // Normalize fields to the format buildUiFromInspectedFields expects
            $normalized = [];
            foreach ($fields as $key => $f) {
                if (! is_array($f)) {
                    continue;
                }
                $f['handle'] = $f['handle'] ?? $f['name'] ?? $key;
                $normalized[] = $f;
            }

            $tenantKey = $manifest['tenant_key'] ?? 'company_id';
            $workflow = $manifest['workflow'] ?? null;

            $ui = $porter->buildUiFromInspectedFields(
                $slice->name,
                $normalized,
                $tenantKey,
                [],
                is_array($workflow) ? $workflow : null,
                $sourcePath
            );

            // buildUiFromInspectedFields returns { directory: {...}, dashboard, forms, show, ... }
            $inferredDir = is_array($ui['directory'] ?? null) ? $ui['directory'] : [];
            $old = $manifest['ui']['directory'] ?? [];
            $manifest['ui'] = $manifest['ui'] ?? [];

            // Preserve real DB field handles: map inferred keys onto existing fields
            // so re-infer does not clobber project_name → title and empty the grid.
            $fieldHandles = [];
            foreach ($normalized as $nf) {
                $fieldHandles[] = (string) ($nf['handle'] ?? '');
            }
            $fieldHandles = array_values(array_filter($fieldHandles));
            $mergedColumns = $this->mergeInferredColumns(
                $old['columns'] ?? [],
                $inferredDir['columns'] ?? [],
                $fieldHandles
            );

            $manifest['ui']['directory'] = array_merge($old, [
                'columns' => $mergedColumns,
                'quick_filters' => $inferredDir['quick_filters'] ?? $old['quick_filters'] ?? [],
                'sidebar_filters' => $inferredDir['sidebar_filters'] ?? $old['sidebar_filters'] ?? [],
                'searchable' => $this->filterSearchableToFields($inferredDir['searchable'] ?? $old['searchable'] ?? [], $fieldHandles),
                'search_placeholder' => $inferredDir['search_placeholder'] ?? $old['search_placeholder'] ?? null,
                'views' => $inferredDir['views'] ?? $old['views'] ?? ['table'],
                'default_view' => $inferredDir['default_view'] ?? $old['default_view'] ?? 'table',
                'inline_edit' => $inferredDir['inline_edit'] ?? $old['inline_edit'] ?? [],
                'bulk_actions' => $inferredDir['bulk_actions'] ?? $old['bulk_actions'] ?? [],
                'row_actions' => $inferredDir['row_actions'] ?? $old['row_actions'] ?? [],
                'summary_cards' => $inferredDir['summary_cards'] ?? $old['summary_cards'] ?? [],
            ]);
            if (! empty($ui['dashboard'])) {
                $manifest['ui']['dashboard'] = $ui['dashboard'];
            }
            if (! empty($ui['show'])) {
                $manifest['ui']['show'] = array_replace_recursive($manifest['ui']['show'] ?? [], $ui['show']);
            }

            if (! $dryRun) {
                \LaraSlice\Core\Discovery\ManifestRepository::writeBoth($json, $manifest);
            }
            $this->line(($dryRun ? '<fg=yellow>would re-infer</> ' : '<fg=green>re-inferred</> ').$slice->name);
            $n++;
        }
        $manager->clearCache();
        $this->info("Re-inferred directory UI on {$n} slice(s)".($skipped ? ", skipped {$skipped} with Studio customizations" : "").".");

        return $n;
    }

    /**
     * Merge inferred directory columns onto real field handles.
     *
     * @param  list<array<string, mixed>>  $existing
     * @param  list<array<string, mixed>>  $inferred
     * @param  list<string>  $fieldHandles
     * @return list<array<string, mixed>>
     */
    protected function mergeInferredColumns(array $existing, array $inferred, array $fieldHandles): array
    {
        $aliases = [
            'title' => ['heading', 'name', 'subject', 'label', 'project_name', 'task'],
            'name' => ['title', 'heading', 'label', 'project_name'],
            'description' => ['desc', 'details', 'summary', 'notes', 'project_summary'],
            'status' => ['board_column', 'state', 'stage', 'project_status', 'invoice_status_code'],
            'due_date' => ['deadline', 'due_on', 'due_at'],
            'start_date' => ['starts_at', 'start_at'],
            'total' => ['amount', 'grand_total', 'price'],
            'amount' => ['total', 'grand_total'],
        ];

        $resolve = function (string $handle) use ($fieldHandles, $aliases): ?string {
            if (in_array($handle, $fieldHandles, true)) {
                return $handle;
            }
            // inferred canonical → actual field
            foreach ($aliases as $canonical => $alts) {
                if ($handle === $canonical || in_array($handle, $alts, true)) {
                    if (in_array($canonical, $fieldHandles, true)) {
                        return $canonical;
                    }
                    foreach ($alts as $a) {
                        if (in_array($a, $fieldHandles, true)) {
                            return $a;
                        }
                    }
                }
            }

            return null;
        };

        $byKey = [];
        // Start from existing columns that still match fields (preserve working keys)
        foreach ($existing as $col) {
            $k = $col['key'] ?? $col['handle'] ?? null;
            if (! $k) {
                continue;
            }
            $resolved = $resolve((string) $k) ?? (in_array($k, $fieldHandles, true) ? $k : null);
            if ($resolved) {
                $col['key'] = $resolved;
                $col['handle'] = $resolved;
                $byKey[$resolved] = $col;
            }
        }

        // Apply inferred formatters onto resolved keys
        foreach ($inferred as $col) {
            $k = $col['handle'] ?? $col['key'] ?? null;
            if (! $k) {
                continue;
            }
            $resolved = $resolve((string) $k);
            if (! $resolved) {
                continue;
            }
            $base = $byKey[$resolved] ?? [
                'key' => $resolved,
                'handle' => $resolved,
                'label' => $col['label'] ?? \Illuminate\Support\Str::headline($resolved),
                'sortable' => true,
            ];
            if (! empty($col['formatter'])) {
                $base['formatter'] = $col['formatter'];
                $base['type'] = $col['formatter'];
            }
            if (! empty($col['badge_from'])) {
                $base['badge_from'] = $col['badge_from'];
            }
            if (! empty($col['breakdown'])) {
                $base['breakdown'] = $col['breakdown'];
            }
            if (! empty($col['inferred_from'])) {
                $base['inferred_from'] = $col['inferred_from'];
            }
            $byKey[$resolved] = $base;
        }

        // If nothing matched, fall back to inferred filtered to field handles only
        if ($byKey === []) {
            foreach ($inferred as $col) {
                $k = $col['handle'] ?? $col['key'] ?? null;
                $resolved = $k ? $resolve((string) $k) : null;
                if ($resolved) {
                    $col['key'] = $resolved;
                    $col['handle'] = $resolved;
                    $byKey[$resolved] = $col;
                }
            }
        }

        return array_values($byKey);
    }

    /**
     * @param  list<string>|mixed  $searchable
     * @param  list<string>  $fieldHandles
     * @return list<string>
     */
    protected function filterSearchableToFields(mixed $searchable, array $fieldHandles): array
    {
        if (! is_array($searchable)) {
            return [];
        }
        $out = [];
        foreach ($searchable as $s) {
            if (is_string($s) && in_array($s, $fieldHandles, true)) {
                $out[] = $s;
            }
        }

        return $out !== [] ? $out : array_slice($fieldHandles, 0, 3);
    }

    /**
     * Merge missing keys from the package config into a published config/laraslice.php.
     * Never overwrites existing user values — only fills gaps (e.g. auth.mfa_enabled).
     */
    protected function mergePublishedLarasliceConfig(): void
    {
        $published = config_path('laraslice.php');
        if (! is_file($published)) {
            return;
        }

        $packageFile = dirname(__DIR__, 2).'/config/laraslice.php';
        if (! is_file($packageFile)) {
            // vendor path
            $packageFile = base_path('vendor/hereafter/laraslice/config/laraslice.php');
        }
        if (! is_file($packageFile)) {
            return;
        }

        $pkg = include $packageFile;
        $app = include $published;
        if (! is_array($pkg) || ! is_array($app)) {
            return;
        }

        $merged = $this->arrayMergeMissing($app, $pkg);
        if ($merged === $app) {
            $this->line('<fg=gray>config</> published laraslice.php already has package keys');
            return;
        }

        $export = var_export($merged, true);
        $content = "<?php\n\nreturn {$export};\n";
        file_put_contents($published, $content);
        $this->line('<fg=green>merged</> missing keys into config/laraslice.php (e.g. auth.mfa_enabled)');
        $this->warn('Re-check config/laraslice.php formatting after merge; prefer php artisan vendor:publish --tag=laraslice-config --force for a full refresh.');
    }

    /**
     * @param  array<string, mixed>  $existing
     * @param  array<string, mixed>  $defaults
     * @return array<string, mixed>
     */
    protected function arrayMergeMissing(array $existing, array $defaults): array
    {
        foreach ($defaults as $key => $value) {
            if (! array_key_exists($key, $existing)) {
                $existing[$key] = $value;
                continue;
            }
            if (is_array($value) && is_array($existing[$key])) {
                $existing[$key] = $this->arrayMergeMissing($existing[$key], $value);
            }
        }

        return $existing;
    }

    /**
     * Phase 3: list JSON-only slices as pending migration.
     */
    protected function reportJsonOnlySlices(): void
    {
        $root = config('laraslice.slices_path', app_path('Slices'));
        if (! is_dir($root)) {
            return;
        }
        $pending = [];
        $it = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS)
        );
        foreach ($it as $file) {
            if (! $file->isFile() || $file->getFilename() !== 'slice.json') {
                continue;
            }
            $dir = dirname($file->getPathname());
            if (! is_file($dir.'/slice.yaml') && ! is_file($dir.'/slice.yml')) {
                $pending[] = $dir;
            }
        }
        if ($pending === []) {
            return;
        }
        $this->warn(count($pending).' slice(s) pending migration (JSON-only):');
        foreach (array_slice($pending, 0, 20) as $dir) {
            $this->line('  '.$dir);
        }
        $this->comment('Convert with: php artisan slice:migrate-json-to-yaml');
    }

}
