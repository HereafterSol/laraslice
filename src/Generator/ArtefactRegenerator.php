<?php

namespace LaraSlice\Generator;

use Illuminate\Support\Str;
use LaraSlice\Core\Discovery\SliceManifest;

/**
 * Artefact regeneration for EXISTING slices (Comparative
 * Fix Programme tooling gap, recorded in FIXES-PHASE-A §5,
 * FIXES-PHASE-B and FIXES-PHASE-C §8).
 *
 * slice:regen-form re-syncs the form views from a corrected
 * Heart, but three generated artefacts bake manifest data
 * in at generation time and had NO re-sync path — phases
 * A–C hand-edited them after every manifest fix:
 *
 *   - the service class (baked repeaterDefinitions(),
 *     relationMultiDefinitions() and validation rules),
 *   - the primary model ($fillable, $casts, relations),
 *   - the show blade (detail view).
 *
 * This service follows the FormRegenerator precedent
 * exactly: the slice is staged whole into a throwaway root
 * (the monolith SliceGenerator reused as-is, fed the
 * Heart's declared relations so staged models carry them),
 * and only those three artefacts are transplanted. Dry-run
 * reporting comes with a per-artefact LOSS detector: named
 * things present in the current artefact that the Heart
 * cannot re-derive (hand-added model methods, $fillable or
 * $casts entries, traits, a hand-pointed $table, service
 * methods/validation fields/repeater handles, show-blade
 * routes/includes/relation calls) — and, since the staging
 * misname fix, relation methods whose staged BINDING
 * drifts from the lived one (same name, different target
 * or kind: 'relation-target:<method>'). A transplant that would
 * destroy a detected loss is refused by default — the
 * caller must explicitly force it.
 *
 * F12 (Day-2 drill, 8 Nov 2026): the CONTRACTS — the
 * Form / Listing / Filter business objects — bake the
 * same manifest data in at generation time (the Form BO's
 * property list IS the request-binding contract:
 * BaseFormBusinessObject::fromArray() only assigns keys
 * that exist as properties, so a field the Heart gained
 * but the BO never did renders, validates, and then
 * silently does not persist). They are regenerated under
 * the same discipline — staged, diffed, loss-detected
 * (hand-added properties/methods/sortable columns are
 * losses, blocked by default) — as CONTRACT_ARTEFACTS.
 * SliceAbsorber deliberately keeps analysing only the
 * original three: absorb's classifications are keyed to
 * model/service/show losses, and folding BO losses into
 * its sweep is a separate decision, not a side effect of
 * this fix.
 *
 * Division of labour with SliceManager::repairSlice():
 * repair is SURGICAL — it heals unresolvable belongsTo
 * modelClass('…') targets in an existing model in place
 * (repairModelRelations, FK evidence chain) without
 * regenerating anything and without trusting the Heart.
 * This regenerator is WHOLESALE — it trusts the current
 * Heart and re-derives the three artefacts from it; the
 * staged model is born with the generator's own FK
 * evidence chain (SliceGenerator::resolveForeignTargetModel
 * + declared relations), so a transplanted model should
 * not need repairModelRelations afterwards. Slices whose
 * models carry hand knowledge the Heart does not express
 * stay on repair (or declare the knowledge and regenerate).
 *
 * Staging fidelity for PHP artefacts: blades carry no
 * namespace, so FormRegenerator can stage with the
 * manifest's FULL namespace as the generator base and
 * nobody notices the tiers being appended twice. A service
 * or model transplanted that way would land in a doubled
 * namespace and the class would never autoload. This
 * regenerator therefore derives the true base namespace
 * and tier options from the manifest's own namespace tail
 * (see stagingPlan()) and passes them into the staging,
 * and — belt and braces — diff() refuses any staged
 * service/model whose namespace line differs from the
 * current file's ('namespace-mismatch' status, never
 * writable, not even with force).
 */
class ArtefactRegenerator
{
    /** @var array<int, string> */
    public const ARTEFACTS = ['service', 'model', 'show'];

    /**
     * The Contracts (business objects), regenerated by
     * slice:regen-artefacts since the F12 fix. Kept OUT of
     * ARTEFACTS so SliceAbsorber — which iterates that
     * const for its loss classifications — keeps analysing
     * exactly the artefacts it always has.
     *
     * @var array<int, string>
     */
    public const CONTRACT_ARTEFACTS = ['form-bo', 'listing-bo', 'filter-bo'];

    /** @return array<int, string> every artefact the regenerator can stage and diff */
    public static function allArtefacts(): array
    {
        return [...self::ARTEFACTS, ...self::CONTRACT_ARTEFACTS];
    }

    private FormRegenerator $formRegenerator;

    public function __construct(?FormRegenerator $formRegenerator = null)
    {
        $this->formRegenerator = $formRegenerator ?? new FormRegenerator;
    }

    /**
     * Stage the slice (via FormRegenerator's staging, with
     * the Heart's declared relations added to the generator
     * options) and locate the artefacts in the staged
     * tree. The staged show blade gets the same route-prefix
     * remap FormRegenerator applies to the form views.
     *
     * @return array{staging: string, sliceDir: string, artefacts: array<string, string>}
     */
    public function stage(SliceManifest $manifest): array
    {
        $extra = [];
        $relations = $this->declaredRelations($manifest);
        if ($relations !== []) {
            $extra['relations'] = $relations;
        }
        $plan = $this->stagingPlan($manifest);
        if ($plan['base'] !== null) {
            // Override the manifest's own tier fields (they
            // can disagree with the namespace — ported Hearts
            // carry legacy tier vocabularies) with the tiers
            // the slice's namespace actually encodes.
            $extra = array_merge($extra, $plan['options']);
        }
        $staged = $this->formRegenerator->stage($manifest, $extra, $plan['base']);

        $artefacts = [];
        foreach (self::allArtefacts() as $key) {
            $path = $staged['sliceDir'].'/'.$this->relativePath($key, $manifest);
            if (file_exists($path)) {
                $artefacts[$key] = $path;
            }
        }
        if (isset($artefacts['show'])) {
            $this->remapShowRoutes($manifest, $artefacts['show']);
        }

        return ['staging' => $staged['staging'], 'sliceDir' => $staged['sliceDir'], 'artefacts' => $artefacts];
    }

    /**
     * Derive the generator's base namespace and tier
     * options from the manifest's full slice namespace:
     * strip the plural slice segment, then the configured
     * slices-namespace prefix; whatever segments remain in
     * between are the tiers (the generator supports at most
     * three: super_domain / app / domain). Returns a null
     * base when the namespace cannot be decomposed this
     * way — staging then falls back to FormRegenerator's
     * behaviour and the namespace guard in diff() refuses
     * any unfaithful PHP artefact.
     *
     * @return array{base: ?string, options: array<string, ?string>}
     */
    private function stagingPlan(SliceManifest $manifest): array
    {
        $full = trim((string) $manifest->getNamespace(), '\\');
        $segments = $full === '' ? [] : explode('\\', $full);
        $plural = Str::studly(Str::plural(SliceName::canonical($manifest->name)));
        if ($segments === [] || end($segments) !== $plural) {
            return ['base' => null, 'options' => []];
        }
        array_pop($segments);
        $bases = array_unique(array_filter([
            trim((string) config('laraslice.slices_namespace', 'App\\Slices'), '\\'),
            'App\\Slices',
            'LaraSlice\\Slices',
        ]));
        foreach ($bases as $base) {
            if (! str_starts_with($full, $base.'\\')) {
                continue;
            }
            $tiers = array_slice($segments, count(explode('\\', $base)));
            if (count($tiers) > 3) {
                return ['base' => null, 'options' => []];
            }
            $options = ['super_domain' => null, 'app' => null, 'domain' => null];
            if (count($tiers) === 3) {
                $options = ['super_domain' => $tiers[0], 'app' => $tiers[1], 'domain' => $tiers[2]];
            } elseif (count($tiers) === 2) {
                $options['app'] = $tiers[0];
                $options['domain'] = $tiers[1];
            } elseif (count($tiers) === 1) {
                $options['domain'] = $tiers[0];
            }

            return ['base' => $base, 'options' => $options];
        }

        return ['base' => null, 'options' => []];
    }

    /**
     * Declared relations the generator should emit methods
     * for: the root model's models[].relations first (that
     * is where the porter writes them), then any top-level
     * Heart relations whose names are not already covered.
     *
     * @return array<int, array<string, mixed>>
     */
    private function declaredRelations(SliceManifest $manifest): array
    {
        $raw = $manifest->raw;
        $root = null;
        foreach ((array) ($raw['models'] ?? []) as $model) {
            if (is_array($model) && ! empty($model['root'])) {
                $root = $model;
                break;
            }
        }
        if ($root === null && is_array($raw['models'][0] ?? null)) {
            $root = $raw['models'][0];
        }
        $byName = [];
        foreach ((array) ($root['relations'] ?? []) as $relation) {
            if (is_array($relation) && ! empty($relation['name'])) {
                $byName[(string) $relation['name']] = $relation;
            }
        }
        foreach ((array) ($raw['relations'] ?? []) as $relation) {
            if (is_array($relation) && ! empty($relation['name']) && ! isset($byName[(string) $relation['name']])) {
                $byName[(string) $relation['name']] = $relation;
            }
        }

        return array_values($byName);
    }

    /**
     * Route-name remap for the staged show blade — the same
     * regression guard FormRegenerator applies to the form
     * views (staging re-derives route names from manifest
     * tier fields, which for ported trees does NOT reproduce
     * the slice's registered names). The slice's CURRENT
     * blades are the lived truth.
     */
    private function remapShowRoutes(SliceManifest $manifest, string $stagedShow): void
    {
        $viewsDir = $manifest->path.'/Resources/views';
        $contents = [];
        foreach (array_merge(FormRegenerator::FORM_VIEWS, ['index.blade.php', 'show.blade.php']) as $view) {
            $path = $viewsDir.'/'.$view;
            if (file_exists($path)) {
                $contents[] = (string) file_get_contents($path);
            }
        }
        $currentPrefix = FormRegenerator::dominantRoutePrefix($contents);
        if ($currentPrefix === null) {
            return; // a brand-new slice: staged names stand
        }
        $content = (string) file_get_contents($stagedShow);
        $stagedPrefix = FormRegenerator::dominantRoutePrefix([$content]);
        if ($stagedPrefix !== null && $stagedPrefix !== $currentPrefix) {
            file_put_contents($stagedShow, str_replace("route('{$stagedPrefix}.", "route('{$currentPrefix}.", $content));
        }
    }

    /**
     * Compare the staged artefacts against the slice's
     * current ones: status, line counts, added/removed line
     * counts, and the loss list per artefact.
     *
     * $keys defaults to the original three artefacts —
     * SliceAbsorber's analysis is defined over exactly
     * those. slice:regen-artefacts passes allArtefacts()
     * so the Contracts are diffed (and transplanted) too.
     *
     * @param  array{artefacts: array<string, string>}  $staged
     * @param  array<int, string>|null  $keys
     * @return array<int, array{artefact: string, file: string, status: string, current_lines: ?int, staged_lines: ?int, added_lines: int, removed_lines: int, lost: array<int, string>}>
     */
    public function diff(SliceManifest $manifest, array $staged, ?array $keys = null): array
    {
        $report = [];
        foreach ($keys ?? self::ARTEFACTS as $key) {
            $relative = $this->relativePath($key, $manifest);
            $current = $manifest->path.'/'.$relative;
            $stagedPath = $staged['artefacts'][$key] ?? null;
            if ($stagedPath === null) {
                $report[] = ['artefact' => $key, 'file' => $relative, 'status' => 'not-generated', 'current_lines' => file_exists($current) ? $this->lineCount((string) file_get_contents($current)) : null, 'staged_lines' => null, 'added_lines' => 0, 'removed_lines' => 0, 'lost' => []];

                continue;
            }
            $stagedContent = (string) file_get_contents($stagedPath);
            if (! file_exists($current)) {
                $report[] = ['artefact' => $key, 'file' => $relative, 'status' => 'new', 'current_lines' => null, 'staged_lines' => $this->lineCount($stagedContent), 'added_lines' => $this->lineCount($stagedContent), 'removed_lines' => 0, 'lost' => []];

                continue;
            }
            $currentContent = (string) file_get_contents($current);
            if ($currentContent === $stagedContent) {
                $report[] = ['artefact' => $key, 'file' => $relative, 'status' => 'identical', 'current_lines' => $this->lineCount($currentContent), 'staged_lines' => $this->lineCount($stagedContent), 'added_lines' => 0, 'removed_lines' => 0, 'lost' => []];

                continue;
            }
            [$removed, $added] = $this->lineDelta($currentContent, $stagedContent);
            $status = 'changed';
            $lost = $this->losses($key, $currentContent, $stagedContent);
            if ($key !== 'show') {
                $currentNs = $this->namespaceLine($currentContent);
                $stagedNs = $this->namespaceLine($stagedContent);
                if ($currentNs !== null && $stagedNs !== null && $currentNs !== $stagedNs) {
                    // Staging could not reproduce this
                    // class's namespace; transplanting it
                    // would break autoloading. Never
                    // writable — not a loss call for the
                    // operator to force past.
                    $status = 'namespace-mismatch';
                    $lost = [];
                }
            }
            $report[] = [
                'artefact' => $key,
                'file' => $relative,
                'status' => $status,
                'current_lines' => $this->lineCount($currentContent),
                'staged_lines' => $this->lineCount($stagedContent),
                'added_lines' => $added,
                'removed_lines' => $removed,
                'lost' => $lost,
            ];
        }

        return $report;
    }

    /**
     * Split a diff report into the rows a --write may
     * transplant and the rows it must refuse: a changed/new
     * artefact with a non-empty loss list is blocked unless
     * $force is given (the operator then knowingly accepts
     * the loss; the backup still preserves the original).
     *
     * @param  array<int, array<string, mixed>>  $rows
     * @return array{writable: array<int, array<string, mixed>>, blocked: array<int, array<string, mixed>>}
     */
    public function writableRows(array $rows, bool $force): array
    {
        $writable = [];
        $blocked = [];
        foreach ($rows as $row) {
            if (! in_array($row['status'], ['changed', 'new'], true)) {
                continue;
            }
            if (($row['lost'] ?? []) !== [] && ! $force) {
                $blocked[] = $row;
            } else {
                $writable[] = $row;
            }
        }

        return ['writable' => $writable, 'blocked' => $blocked];
    }

    /**
     * Copy the given staged artefacts over the slice's,
     * backing the originals up first (relative subpaths
     * preserved under the backup dir). Returns the backup
     * directory and the relative paths written.
     *
     * @param  array{artefacts: array<string, string>}  $staged
     * @param  array<int, array<string, mixed>>  $rows
     * @return array{backupDir: string, written: array<int, string>}
     */
    public function apply(SliceManifest $manifest, array $staged, array $rows, string $backupRoot): array
    {
        $backupDir = rtrim($backupRoot, '/').'/'.$manifest->name.'-'.date('YmdHis');
        if (! is_dir($backupDir)) {
            mkdir($backupDir, 0755, true);
        }
        $written = [];
        foreach ($rows as $row) {
            $relative = (string) $row['file'];
            $target = $manifest->path.'/'.$relative;
            if (file_exists($target)) {
                $backupPath = $backupDir.'/'.$relative;
                if (! is_dir(dirname($backupPath))) {
                    mkdir(dirname($backupPath), 0755, true);
                }
                copy($target, $backupPath);
            }
            if (! is_dir(dirname($target))) {
                mkdir(dirname($target), 0755, true);
            }
            copy($staged['artefacts'][(string) $row['artefact']], $target);
            $written[] = $relative;
        }

        return ['backupDir' => $backupDir, 'written' => $written];
    }

    public function discardStaging(string $staging): void
    {
        $this->formRegenerator->discardStaging($staging);
    }

    private function relativePath(string $key, SliceManifest $manifest): string
    {
        $studly = SliceName::canonical($manifest->name);

        return match ($key) {
            'service' => "Services/{$studly}SliceService.php",
            'model' => "Models/{$studly}.php",
            'show' => 'Resources/views/show.blade.php',
            'form-bo' => "Contracts/{$studly}FormBusinessObject.php",
            'listing-bo' => "Contracts/{$studly}ListingBusinessObject.php",
            'filter-bo' => "Contracts/{$studly}FilterBusinessObject.php",
        };
    }

    private function lineCount(string $content): int
    {
        return $content === '' ? 0 : count(explode("\n", $content));
    }

    /**
     * Multiset line delta: [lines only in $current, lines
     * only in $staged] — a report-grade count, not a patch.
     *
     * @return array{0: int, 1: int}
     */
    private function lineDelta(string $current, string $staged): array
    {
        $currentCounts = array_count_values(explode("\n", $current));
        $stagedCounts = array_count_values(explode("\n", $staged));
        $removed = 0;
        foreach ($currentCounts as $line => $count) {
            $removed += max(0, $count - ($stagedCounts[$line] ?? 0));
        }
        $added = 0;
        foreach ($stagedCounts as $line => $count) {
            $added += max(0, $count - ($currentCounts[$line] ?? 0));
        }

        return [$removed, $added];
    }

    /**
     * The loss list for one artefact: named things present
     * in the current artefact that the staged regeneration
     * (and therefore the Heart behind it) cannot re-derive.
     *
     * @return array<int, string>
     */
    private function losses(string $key, string $current, string $staged): array
    {
        return match ($key) {
            'model' => $this->modelLosses($current, $staged),
            'service' => $this->serviceLosses($current, $staged),
            'show' => $this->showLosses($current, $staged),
            'form-bo', 'listing-bo' => $this->contractLosses($current, $staged, false),
            'filter-bo' => $this->contractLosses($current, $staged, true),
        };
    }

    /**
     * Losses for a business object: named members present
     * in the current BO that the staged regeneration (and
     * therefore the Heart) cannot re-derive — hand-added
     * properties (the F12 failure mode in reverse: a BO
     * property for a field the Heart does not declare is
     * hand knowledge, declare the field or lose the
     * property), hand-added methods, hand-used traits,
     * and, for the Filter BO, hand-added sortable columns.
     * Name-keyed like the model/service detectors: a
     * property present on both sides is the Heart's to
     * shape (type/default flow from the declaration); a
     * property present ONLY in the current file is not.
     *
     * @return array<int, string>
     */
    private function contractLosses(string $current, string $staged, bool $filter): array
    {
        $lost = [];
        foreach (array_diff($this->methodNames($current), $this->methodNames($staged)) as $name) {
            $lost[] = 'method:'.$name;
        }
        foreach (array_diff($this->propertyNames($current), $this->propertyNames($staged)) as $name) {
            $lost[] = 'property:'.$name;
        }
        foreach (array_diff($this->classTraits($current), $this->classTraits($staged)) as $trait) {
            $lost[] = 'trait:'.$trait;
        }
        if ($filter) {
            foreach (array_diff($this->sortableColumns($current), $this->sortableColumns($staged)) as $column) {
                $lost[] = 'sortable:'.$column;
            }
        }

        return $lost;
    }

    /**
     * Declared property names in a PHP class file:
     * visibility-prefixed typed (or untyped) property
     * declarations. Method bodies never carry visibility
     * modifiers on variables, so a file-wide scan is safe
     * for generated/hand-edited class files.
     *
     * @return array<int, string>
     */
    private function propertyNames(string $php): array
    {
        if (! preg_match_all('/(?:public|protected|private)\s+(?:static\s+)?(?:readonly\s+)?(?:[?\\\\\w][\w\\\\|?]*\s+)?\$(\w+)\s*(?:=[^;]*)?;/', $php, $m)) {
            return [];
        }

        return array_values(array_unique($m[1]));
    }

    /**
     * Column names in the Filter BO's sortableColumns()
     * return list.
     *
     * @return array<int, string>
     */
    private function sortableColumns(string $php): array
    {
        $body = $this->methodBody($php, 'sortableColumns');
        if ($body === null || ! preg_match_all("/'([^']+)'/", $body, $m)) {
            return [];
        }

        return array_values(array_unique($m[1]));
    }

    /** @return array<int, string> */
    private function modelLosses(string $current, string $staged): array
    {
        $lost = [];
        foreach (array_diff($this->methodNames($current), $this->methodNames($staged)) as $name) {
            $lost[] = 'method:'.$name;
        }
        // Target drift on same-named relations: the name
        // diff above is blind to a staged method that keeps
        // the lived method's name but binds a DIFFERENT
        // target — staging's FK evidence chain re-derived
        // EmployeeDetails' department() to a nonexistent
        // Department where the lived model points at Team,
        // and a transplant would have broken the relation
        // while reporting "no losses". A drifted target is
        // a loss-class finding: it blocks a default --write
        // exactly like a missing method does.
        $stagedSignatures = $this->relationSignatures($staged);
        foreach ($this->relationSignatures($current) as $name => $signature) {
            $stagedSignature = $stagedSignatures[$name] ?? null;
            if ($stagedSignature === null) {
                continue; // absent on the staged side — the method-name diff speaks for it
            }
            if ($signature['kind'] !== $stagedSignature['kind'] || $signature['targets'] !== $stagedSignature['targets']) {
                $lost[] = 'relation-target:'.$name;
            }
        }
        foreach (array_diff($this->stringListProperty($current, 'fillable'), $this->stringListProperty($staged, 'fillable')) as $column) {
            $lost[] = 'fillable:'.$column;
        }
        foreach (array_diff($this->castKeys($current), $this->castKeys($staged)) as $column) {
            $lost[] = 'cast:'.$column;
        }
        foreach (array_diff($this->classTraits($current), $this->classTraits($staged)) as $trait) {
            $lost[] = 'trait:'.$trait;
        }
        $currentTable = $this->tableName($current);
        $stagedTable = $this->tableName($staged);
        if ($currentTable !== null && $stagedTable !== null && $currentTable !== $stagedTable) {
            $lost[] = 'table:'.$currentTable;
        }

        return $lost;
    }

    /** @return array<int, string> */
    private function serviceLosses(string $current, string $staged): array
    {
        $lost = [];
        foreach (array_diff($this->methodNames($current), $this->methodNames($staged)) as $name) {
            $lost[] = 'method:'.$name;
        }
        foreach (array_diff($this->validationFields($current), $this->validationFields($staged)) as $field) {
            $lost[] = 'validation:'.$field;
        }
        foreach (array_diff($this->exportedTopKeys($this->methodBody($current, 'repeaterDefinitions')), $this->exportedTopKeys($this->methodBody($staged, 'repeaterDefinitions'))) as $handle) {
            $lost[] = 'repeater:'.$handle;
        }
        foreach (array_diff($this->exportedTopKeys($this->methodBody($current, 'relationMultiDefinitions')), $this->exportedTopKeys($this->methodBody($staged, 'relationMultiDefinitions'))) as $handle) {
            $lost[] = 'relation-multi:'.$handle;
        }

        return $lost;
    }

    /** @return array<int, string> */
    private function showLosses(string $current, string $staged): array
    {
        $lost = [];
        foreach (array_diff($this->bladeTokens($current, "/route\\('([^']+)'/", 'route:'), $this->bladeTokens($staged, "/route\\('([^']+)'/", 'route:')) as $token) {
            $lost[] = $token;
        }
        foreach (array_diff($this->bladeTokens($current, "/@include(?:If)?\\(\\s*'([^']+)'/", 'include:'), $this->bladeTokens($staged, "/@include(?:If)?\\(\\s*'([^']+)'/", 'include:')) as $token) {
            $lost[] = $token;
        }
        foreach (array_diff($this->bladeTokens($current, '/\\$(?:record|item)->([A-Za-z_]\\w*)\\(\\)/', 'relation-call:'), $this->bladeTokens($staged, '/\\$(?:record|item)->([A-Za-z_]\\w*)\\(\\)/', 'relation-call:')) as $token) {
            $lost[] = $token;
        }

        return $lost;
    }

    /** @return array<int, string> */
    private function bladeTokens(string $blade, string $pattern, string $prefix): array
    {
        if (! preg_match_all($pattern, $blade, $m)) {
            return [];
        }

        return array_values(array_unique(array_map(fn (string $name) => $prefix.$name, $m[1])));
    }

    /** @return array<int, string> */
    private function methodNames(string $php): array
    {
        if (! preg_match_all('/function\s+([A-Za-z_]\w*)\s*\(/', $php, $m)) {
            return [];
        }

        return array_values(array_unique($m[1]));
    }

    private function methodBody(string $php, string $method): ?string
    {
        $pos = strpos($php, 'function '.$method.'(');
        if ($pos === false) {
            return null;
        }
        $open = strpos($php, '{', $pos);
        if ($open === false) {
            return null;
        }
        $depth = 0;
        $length = strlen($php);
        for ($i = $open; $i < $length; $i++) {
            if ($php[$i] === '{') {
                $depth++;
            } elseif ($php[$i] === '}') {
                $depth--;
                if ($depth === 0) {
                    return substr($php, $open, $i - $open + 1);
                }
            }
        }

        return null;
    }

    /**
     * Relation signatures per method name: the relation
     * kind and the ordered target model names the method
     * body resolves — modelClass('…') literals in body
     * order (the generator/porter idiom), or a leading
     * ::class target. Methods whose bodies are not plain
     * relation returns are absent from the map, so drift
     * is only ever reported when BOTH sides parse.
     *
     * @return array<string, array{kind: string, targets: array<int, string>}>
     */
    private function relationSignatures(string $php): array
    {
        $signatures = [];
        foreach ($this->methodNames($php) as $name) {
            $body = $this->methodBody($php, $name);
            if ($body === null) {
                continue;
            }
            if (! preg_match('/\$this->(belongsTo|hasMany|hasOne|belongsToMany|hasManyThrough|hasOneThrough|morphTo|morphOne|morphMany|morphToMany|morphedByMany)\s*\(/', $body, $km)) {
                continue;
            }
            $targets = [];
            if (preg_match_all("/modelClass\(\s*'([^']+)'\s*\)/", $body, $mm)) {
                $targets = $mm[1];
            } elseif (preg_match('/\$this->\w+\s*\(\s*([A-Za-z_\\\\][\w\\\\]*)::class/', $body, $cm)) {
                $targets = [basename(str_replace('\\', '/', $cm[1]))];
            }
            if ($targets === []) {
                continue;
            }
            $signatures[$name] = ['kind' => $km[1], 'targets' => array_values($targets)];
        }

        return $signatures;
    }

    /**
     * Top-level keys of a var_export'ed array in a method
     * body: nested levels are indented deeper, so the keys
     * at the smallest indent are the top level.
     *
     * @return array<int, string>
     */
    private function exportedTopKeys(?string $body): array
    {
        if ($body === null || ! preg_match_all('/^([ \t]*)\'?([A-Za-z0-9_]+)\'?\s*=>/m', $body, $m, PREG_SET_ORDER)) {
            return [];
        }
        $min = null;
        foreach ($m as $row) {
            $indent = strlen($row[1]);
            if ($min === null || $indent < $min) {
                $min = $indent;
            }
        }
        $keys = [];
        foreach ($m as $row) {
            if (strlen($row[1]) === $min) {
                $keys[] = $row[2];
            }
        }

        return array_values(array_unique($keys));
    }

    /**
     * Field names carrying rules in the generated validate()
     * method — every quoted array key in its body.
     *
     * @return array<int, string>
     */
    private function validationFields(string $php): array
    {
        $body = $this->methodBody($php, 'validate');
        if ($body === null || ! preg_match_all("/'([A-Za-z0-9_.]+)'\\s*=>/", $body, $m)) {
            return [];
        }

        return array_values(array_unique($m[1]));
    }

    /** @return array<int, string> */
    private function stringListProperty(string $php, string $property): array
    {
        // Generated code bakes these via var_export: `array ( 0 => 'x', … )`.
        if (! preg_match('/\$'.$property.'\s*=\s*(?:array\s*\(|\[)(.*?)(?:\)|\])\s*;/s', $php, $m)) {
            return [];
        }
        if (! preg_match_all("/'([^']+)'/", $m[1], $mm)) {
            return [];
        }

        return array_values(array_unique($mm[1]));
    }

    /** @return array<int, string> */
    private function castKeys(string $php): array
    {
        if (! preg_match('/\$casts\s*=\s*(?:array\s*\(|\[)(.*?)(?:\)|\])\s*;/s', $php, $m)) {
            return [];
        }
        if (! preg_match_all("/'([^']+)'\s*=>/", $m[1], $mm)) {
            return [];
        }

        return array_values(array_unique($mm[1]));
    }

    /** @return array<int, string> */
    private function classTraits(string $php): array
    {
        $classPos = strpos($php, 'class ');
        if ($classPos === false) {
            return [];
        }
        $open = strpos($php, '{', $classPos);
        if ($open === false) {
            return [];
        }
        // Trait use statements sit at the top of the class body.
        $head = substr($php, $open, 4000);
        if (! preg_match_all('/^\s*use\s+([A-Za-z\\\\]+)(?:\s+as\s+\w+)?;/m', $head, $m)) {
            return [];
        }

        return array_values(array_unique(array_map(fn (string $fqn) => basename(str_replace('\\', '/', $fqn)), $m[1])));
    }

    private function tableName(string $php): ?string
    {
        return preg_match("/protected \\\$table = '([^']+)'/", $php, $m) ? $m[1] : null;
    }

    private function namespaceLine(string $php): ?string
    {
        return preg_match('/^namespace\s+([^;]+);/m', $php, $m) ? trim($m[1]) : null;
    }
}
