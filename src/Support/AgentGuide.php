<?php

namespace LaraSlice\Support;

use Illuminate\Support\Facades\File;

/**
 * Generates the app-root AGENTS.md — the always-loaded,
 * index-form guide an AI agent reads first (the Boost
 * pattern: one canonical AGENTS.md, plus a CLAUDE.md
 * import shim that points at it).
 *
 * The guide is deliberately an INDEX (≤ ~8KB): the
 * trilogy in one line each, where things live, the happy
 * paths, and the full command table from CommandIndex.
 * Depth lives in the skills (`.agents/skills/`, published
 * by `laraslice:skill:publish`) — the guide routes to
 * them, it does not repeat them.
 *
 * Existing files are never overwritten unless forced:
 * an app's AGENTS.md may be hand-curated.
 */
class AgentGuide
{
    /**
     * Write AGENTS.md + the CLAUDE.md shim into the app root.
     *
     * @return array{AGENTS.md: string, CLAUDE.md: string} status per file: written|kept
     */
    public static function write(bool $force = false): array
    {
        $status = [];

        $agentsPath = base_path('AGENTS.md');
        if ($force || ! File::exists($agentsPath)) {
            File::put($agentsPath, static::render(CommandIndex::collect()));
            $status['AGENTS.md'] = 'written';
        } else {
            $status['AGENTS.md'] = 'kept';
        }

        $claudePath = base_path('CLAUDE.md');
        if ($force || ! File::exists($claudePath)) {
            File::put($claudePath, "@AGENTS.md\n");
            $status['CLAUDE.md'] = 'written';
        } else {
            $status['CLAUDE.md'] = 'kept';
        }

        return $status;
    }

    /** @param  array  $commands  rows from CommandIndex::collect() */
    public static function render(array $commands): string
    {
        $appName = (string) (config('app.name') ?: 'This application');
        $laravel = function_exists('app') ? app()->version() : 'unknown';
        $php = PHP_VERSION;
        $table = CommandIndex::toMarkdownTable($commands);

        return <<<MD
        # AGENTS.md — {$appName} (LaraSlice)

        Generated by LaraSlice (`slice:install`; regenerate with
        `php artisan slice:index --agents --force`). Index-form on
        purpose: routes and pointers, not prose. Depth lives in the
        skills under `.agents/skills/` (publish them with
        `php artisan laraslice:skill:publish`).

        ## What this system is

        A system declared, not scattered:

        - **Mind** — `system.yaml`: what the system is (identity, design/Soul, localization).
        - **Body** — `*.ui.yaml`: what people see and do.
        - **Heart** — `slice.yaml` per slice under `app/Slices/`: how each part behaves; the sole runtime truth. Fields live ONLY here.
        - **Soul** — the design identity, declared in the Mind (`design.kit`: `house` by default; `replica` for source-faithful ports).

        ## Stack

        PHP {$php} · Laravel {$laravel} · LaraSlice. Verify apps by
        content, not status codes. Run the suite before claiming done.

        ## Happy paths (one per audience)

        - **New slice:** `php artisan slice:make {Name}` → declare fields in its `slice.yaml` → `php artisan slice:cache`. New project? The `laraslice-start` skill: pre-build dossier (§28) → Mind → first slice.
        - **Port an existing system:** the `laraslice-port` skill — analyze → compose → port (`slice:port`) → prove with the five gates.
        - **Operate:** the `laraslice-operate` skill + `php artisan slice:operate health`.

        ## The five gates (porting/replica work)

        **S**tructure (schema closure = 0) · **D**ata (values match by natural key) ·
        **F**urniture (elements + shell, audited element by element) · **T**asks
        (real per-persona journeys, values asserted) · **V**isual (looks like the
        source; literal for replicas). Status = the lowest unverified gate, quoted
        ONLY from the port's `REPLICA-STATUS.md`. Converge = `slice:drift` zero
        errors + the gates; never self-report.

        ## Commands

        Machine index: `php artisan slice:index --format=json`.

        {$table}

        ## Standing rules

        - Fix at the layer that owns it (kit / pattern / declaration / generator) — never per-slice hacks or per-page CSS.
        - Never overwrite this file by hand-editing around the generator: regenerate, or curate deliberately (install keeps an existing AGENTS.md unless `--force`).
        - Secrets go through the app's secure flows, never into files or chat.

        MD;
    }
}
